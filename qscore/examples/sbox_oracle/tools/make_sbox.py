"""Generate circuits/sbox_layer_4x.qasm: four PRESENT S-boxes on 16 data qubits + 4 clean ancillas.

Recipe pinned by CP-0015 (specs/14 §3.2): basic (unidirectional, output-side) MMD, rows i = 0..15,
bits LSB-first, gates applied to the outputs and emitted in reverse. S-box k acts on data qubits
4k..4k+3 (bit 0 = qubit 4k) with ancilla 16+k; a 3-control Toffoli becomes
ccx(a,b,anc); ccx(anc,c,t); ccx(a,b,anc). The output is verified classically over all 16 inputs
per S-box (ancilla must return to 0) before it is written.

Run: uv run python examples/sbox_oracle/tools/make_sbox.py
"""

from __future__ import annotations

from pathlib import Path

S = [0xC, 0x5, 0x6, 0xB, 0x9, 0x0, 0xA, 0xD, 0x3, 0xE, 0xF, 0x8, 0x4, 0x7, 0x1, 0x2]
N_SBOXES = 4
OUT = Path(__file__).resolve().parents[1] / "circuits" / "sbox_layer_4x.qasm"

Mct = tuple[tuple[int, ...], int]  # (controls, target) on S-box bit positions
Gate = tuple[str, tuple[int, ...]]  # (name, qubits); the last qubit is the target


def _bits(x: int) -> list[int]:
    return [b for b in range(4) if x >> b & 1]


def _apply(x: int, controls: tuple[int, ...], target: int) -> int:
    return x ^ (1 << target) if all(x >> c & 1 for c in controls) else x


def mmd_basic(perm: list[int]) -> list[Mct]:
    f = list(perm)
    gates: list[Mct] = []
    for i in range(16):
        for j in _bits(i & ~f[i]):
            g = (tuple(_bits(f[i])), j)
            gates.append(g)
            f = [_apply(y, *g) for y in f]
        for j in _bits(f[i] & ~i):
            g = (tuple(_bits(i)), j)
            gates.append(g)
            f = [_apply(y, *g) for y in f]
        if f[i] != i:
            raise RuntimeError(f"MMD failed at row {i}")
    if f != list(range(16)):
        raise RuntimeError("MMD did not reach the identity")
    return list(reversed(gates))


def lower(mcts: list[Mct], k: int) -> list[Gate]:
    q = [4 * k + b for b in range(4)]
    anc = 16 + k
    out: list[Gate] = []
    for controls, target in mcts:
        cs, t = [q[c] for c in controls], q[target]
        if len(cs) == 0:
            out.append(("x", (t,)))
        elif len(cs) == 1:
            out.append(("cx", (cs[0], t)))
        elif len(cs) == 2:
            out.append(("ccx", (cs[0], cs[1], t)))
        elif len(cs) == 3:
            a, b, c = cs
            out += [("ccx", (a, b, anc)), ("ccx", (anc, c, t)), ("ccx", (a, b, anc))]
        else:
            raise RuntimeError(f"unexpected {len(cs)}-control gate")
    return out


def run_classical(gates: list[Gate], state: int) -> int:
    for _, qubits in gates:
        *controls, target = qubits
        if all(state >> c & 1 for c in controls):
            state ^= 1 << target
    return state


def verify(gates: list[Gate], k: int) -> None:
    for x in range(16):
        y = run_classical(gates, x << (4 * k))
        if y != S[x] << (4 * k):  # data bits map through S; ancilla and other S-boxes stay 0
            raise RuntimeError(f"S-box {k}: input {x:#x} gave state {y:#x}, want {S[x]:#x}")


def main() -> None:
    mcts = mmd_basic(S)
    lines = [
        "OPENQASM 2.0;",
        'include "qelib1.inc";',
        "// Four PRESENT S-boxes (basic MMD, CP-0015); data q[0..15], clean ancillas q[16..19].",
        "// Generated by examples/sbox_oracle/tools/make_sbox.py; do not edit by hand.",
        "qreg q[20];",
    ]
    total_ccx = 0
    for k in range(N_SBOXES):
        gates = lower(mcts, k)
        verify(gates, k)
        total_ccx += sum(1 for name, _ in gates if name == "ccx")
        lines += [f"{name} {','.join(f'q[{i}]' for i in qs)};" for name, qs in gates]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({total_ccx} ccx, verified on all inputs)")


if __name__ == "__main__":
    main()
